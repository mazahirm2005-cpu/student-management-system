-- Student Information & Management System
-- Oracle Database Schema
-- =====================================================

-- USERS TABLE
CREATE TABLE USERS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    FULL_NAME VARCHAR2(1020),
    FATHER_NAME VARCHAR2(1020),
    EMAIL VARCHAR2(1020),
    PHONE VARCHAR2(1020),
    DOB DATE,
    GENDER VARCHAR2(1020),
    CNIC VARCHAR2(1020),
    ADDRESS VARCHAR2(255),
    USERNAME VARCHAR2(1020) UNIQUE,
    PASSWORD VARCHAR2(255),
    ROLE VARCHAR2(1020)
);


-- ACTIVITY LOGS TABLE
CREATE TABLE ACTIVITY_LOGS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USERNAME VARCHAR2(50),
    ROLE VARCHAR2(20),
    ACTION VARCHAR2(100),
    DESCRIPTION VARCHAR2(500),
    ACTIVITY_TIME TIMESTAMP(6)
);